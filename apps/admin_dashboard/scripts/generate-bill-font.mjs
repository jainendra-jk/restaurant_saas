/**
 * Fetches Roboto-Regular.ttf and Roboto-Bold.ttf and writes base64 to src/app/bill/fonts/robotoBase64.ts
 * so the customer bill PDF can render Unicode (e.g. ₹) with bold for title and TOTAL.
 * Run: node scripts/generate-bill-font.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_PATH = path.join(__dirname, '..', 'src', 'app', 'bill', 'fonts', 'robotoBase64.ts');
const ROBOTO_REGULAR_URL = 'https://github.com/googlefonts/roboto/raw/main/src/hinted/Roboto-Regular.ttf';
const ROBOTO_BOLD_URL = 'https://github.com/googlefonts/roboto/raw/main/src/hinted/Roboto-Bold.ttf';

async function fetchBase64(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error('Failed to fetch: ' + res.status + ' ' + res.statusText);
  const buf = Buffer.from(await res.arrayBuffer());
  return buf.toString('base64');
}

async function main() {
  console.log('Fetching Roboto-Regular.ttf...');
  const regularBase64 = await fetchBase64(ROBOTO_REGULAR_URL);
  console.log('Fetching Roboto-Bold.ttf...');
  const boldBase64 = await fetchBase64(ROBOTO_BOLD_URL);
  const content = `/**
 * Base64-encoded Roboto fonts for jsPDF (Unicode support, e.g. ₹).
 * Generated by: node scripts/generate-bill-font.mjs
 * When ROBOTO_REGULAR_BASE64 is empty, the bill falls back to Helvetica.
 */
export const ROBOTO_REGULAR_BASE64 = ${JSON.stringify(regularBase64)};
export const ROBOTO_BOLD_BASE64 = ${JSON.stringify(boldBase64)};
export const UNICODE_FONT_FILENAME = 'Roboto-Regular.ttf';
export const UNICODE_FONT_BOLD_FILENAME = 'Roboto-Bold.ttf';
export const UNICODE_FONT_NAME = 'Roboto';
`;
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, content, 'utf8');
  console.log('Wrote', OUT_PATH);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
