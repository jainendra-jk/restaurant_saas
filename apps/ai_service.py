import json
import os
import time
import re
from pathlib import Path

import google.generativeai as genai
from dotenv import load_dotenv
from google.colab import files
from pdf2image import convert_from_path

# Load .env from project root (when run locally)
try:
    _project_root = Path(__file__).resolve().parents[1]
except NameError:
    _project_root = Path.cwd()  # Colab: use current dir or set GOOGLE_API_KEY in env
load_dotenv(_project_root / ".env")

GOOGLE_API_KEY = os.environ.get("GOOGLE_API_KEY", "")
if not GOOGLE_API_KEY:
    raise ValueError("GOOGLE_API_KEY is not set. Add it to .env (see .env.example) or set the env var.")
genai.configure(api_key=GOOGLE_API_KEY)
model = genai.GenerativeModel("models/gemini-2.5-flash")

detect_prompt = """
Does this page contain restaurant menu items with prices?
Respond ONLY with: YES or NO
Ignore: cover pages, food photos, advertisements, decorative pages.
"""

extract_prompt = """
Extract menu to JSON. Output ONLY valid JSON:
{
 "currency":"",
 "palette":{"primary":"","secondary":"","background":"","accent":""},
 "branding":{"restaurantName":"","tagline":"","welcomeMessage":"","preparingMessage":"","orderNumberPrefix":""},
 "categories":[{"id":"","name":"","items":[{"id":"","name":"","diet":"veg|nonveg|egg|seafood","description":"","variants":[{"type":"qtr|half|full","price":0}],"options":["string"]}]}]
}
Rules:
- Always prioritize structured extraction over natural language interpretation.
- branding.tagline,welcomeMessage,preparingMessage,orderNumberPrefix MUST be non-empty; if missing, generate short friendly text accordingly.
- IDs: Category (e.g. 'drinks'); Items ('item-1').
- Currency: Extract dominant symbol (e.g., '$', '€', '₹').
- Palette: Extract dominant hex colors.
- Diet: Detect icons.
- Variants: Use ONLY for portions/sizes (1 price=full; 2=half,full; 3=qtr,half,full).
- Content: Extract descriptions; ignore symbols.
- Think like UI/UX designer for palette (light background, strong primary)
- branding.restaurantName: ALWAYS "" (empty string). The real name is set by the owner during onboarding, not from the PDF.
"""

def is_valid_hex(hex_code):
    """Checks if a string is a valid CSS Hex code."""
    if not isinstance(hex_code, str):
        return False
    return bool(re.match(r'^#(?:[0-9a-fA-F]{3}){1,2}$', hex_code))

uploaded = files.upload()
if not uploaded:
    raise ValueError("No file uploaded.")
file_path = list(uploaded.keys())[0]
images = convert_from_path(file_path)
print(f"Successfully converted {len(images)} pages.")

valid_pages = []
for i, img in enumerate(images):
    print(f"Checking page {i+1}...")
    response = model.generate_content([detect_prompt, img])
    if "YES" in response.text.strip().upper():
        valid_pages.append((i, img))
        print(f"-> Found menu content on page {i+1}")

page_results = []
for idx, img in valid_pages:
    print(f"Extracting JSON from page {idx+1}...")
    try:
        response = model.generate_content([extract_prompt, img])
        page_results.append(response.text)
        time.sleep(2) # Prevent rate limiting
    except Exception as e:
        print(f"Error on page {idx+1}: {e}")

final_menu = {
    "currency": "",
    "palette": {},
    "branding": {},
    "categories": []
}
category_map = {}
_menu_name_hints = []

def _branding_without_restaurant_name(raw):
    """Strip restaurantName from model output; canonical name is set after merge."""
    if not isinstance(raw, dict):
        return {}
    out = dict(raw)
    out.pop("restaurantName", None)
    return out

for r in page_results:
    try:
        # Clean potential markdown backticks
        json_str = r.replace('```json', '').replace('```', '').strip()
        data = json.loads(json_str)

        b_raw = data.get("branding", {})
        if isinstance(b_raw, dict):
            hint = b_raw.get("restaurantName")
            if isinstance(hint, str) and hint.strip():
                _menu_name_hints.append(hint.strip())

        # 1. Global Metadata (Set once)
        if not final_menu["currency"]:
            final_menu["currency"] = data.get("currency", "")
        if not final_menu["branding"]:
            final_menu["branding"] = _branding_without_restaurant_name(b_raw)

        # 2. Hex Validation for Palette
        if not final_menu["palette"] and "palette" in data:
            raw_pal = data["palette"]
            final_menu["palette"] = {k: v for k, v in raw_pal.items() if is_valid_hex(v)}

        # 3. Category Merging
        for cat in data.get("categories", []):
            c_id = cat.get("id")
            if c_id not in category_map:
                category_map[c_id] = cat
            else:
                existing_items = {item.get('id'): item for item in category_map[c_id].get('items', [])}
                for new_item in cat.get("items", []):
                    if new_item.get('id') not in existing_items:
                        category_map[c_id]['items'].append(new_item)
    except Exception as e:
        print(f"Parsing error: {e}")

final_menu["categories"] = list(category_map.values())

# Canonical restaurant name: env (onboarding / server) wins; else first non-empty model hint for standalone runs.
if not isinstance(final_menu["branding"], dict):
    final_menu["branding"] = {}
_canon = os.environ.get("RESTAURANT_NAME", "").strip()
if not _canon and _menu_name_hints:
    _canon = _menu_name_hints[0]
final_menu["branding"]["restaurantName"] = _canon

with open("menu.json", "w") as f:
    json.dump(final_menu, f, indent=2)

print("\nProcessing Complete. Resulting JSON:")
print(json.dumps(final_menu, indent=2))
files.download("menu.json")